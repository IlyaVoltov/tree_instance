class TreeNode: # Класс для представления узла дерева
    def __init__(self, value): # Инициализация узла с его значением и списком детей
        self.value = value # Значение узла
        self.children = [] # Список детей узла, изначально пустой
    
    def add_child(self, child_node): # Метод для добавления ребёнка к узлу
        self.children.append(child_node) # Добавляем ребёнка в список детей узла
    
    def print_tree(self, level=0): # Метод для печати дерева с отступами, показывающими структуру дерева
        print("  " * level + "└── " + self.value) # Выводим значение узла с отступом, который зависит от уровня в дереве (чем глубже, тем больше отступ) и символом "└──" для визуального представления структуры дерева
        for child in self.children: # Рекурсивно печатаем всех детей
            child.print_tree(level + 1) # Рекурсивный вызов для печати детей с увеличенным уровнем отступа
    
    def recommend_beverage(self): # Метод для интерактивного опроса пользователя, который рекомендует напиток на основе выбора
        if not self.children: # Если у узла нет детей, значит это конечный напиток
            print(f"\nРешение принято Напиток: {self.value}") # Выводим выбранный напиток и завершаем рекурсию
            return # Конец рекурсии
        
        print(f"\n{self.value}? Выбери один из вариантов:") # Выводим текущий узел и предлагаем выбрать из его детей
        for i, child in enumerate(self.children, 1): # Перечисляем детей с нумерацией для удобства выбора
            print(f"  {i}. {child.value}") # Выводим каждый вариант с его номером для выбора пользователем
        
        # Защита от неверного ввода
        while True: # Бесконечный цикл, который будет продолжаться, пока пользователь не введёт корректный номер
            try: # Пытаемся преобразовать ввод в целое число
                choice = int(input("Введи номер: ")) # Считываем ввод пользователя и преобразуем его в число
                if 1 <= choice <= len(self.children): # Проверяем, что введённый номер соответствует одному из вариантов
                    selected_child = self.children[choice - 1] # Получаем выбранного ребёнка на основе введённого номера (учитывая, что нумерация начинается с 1)
                    selected_child.recommend_beverage()  # Рекурсивный вызов метода для выбранного ребёнка, чтобы продолжить опрос дальше по дереву
                    break # Выходим из цикла после успешного выбора
                else: # Если введённый номер не соответствует ни одному из вариантов, выводим сообщение об ошибке и предлагаем попробовать снова
                    print("Нет такого варианта. Попробуй снова.") # Сообщение об ошибке для пользователя, если он ввёл число, которое не соответствует ни одному из вариантов
            except ValueError: # Если пользователь ввёл не число, а текст или другой некорректный ввод, обработаем исключение и выведем сообщение об ошибке
                print("Введи число, а не текст!") # Сообщение об ошибке для пользователя, если он ввёл не число, а текст или другой некорректный ввод, и предложение попробовать снова


# Построение дерева «Напитки»
